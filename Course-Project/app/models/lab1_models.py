"""Data contracts for Lab 1: Clarify -> Plan -> Revise."""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Literal, Optional
from pydantic import BaseModel, Field, model_validator


class MissingInfoCategory(str, Enum):
    """Categories of course workspace dimensions that can be missing or underspecified."""
    SCHEDULE_PACING = "schedule_pacing"
    MATERIALS_PREREQUISITES = "materials_prerequisites"
    ASSIGNMENTS_LABS = "assignments_labs"
    GRADING_WEIGHTS = "grading_weights"
    TA_SUPPORT = "ta_support"


class FacultyCourseRequest(BaseModel):
    """Initial faculty request for setting up a course workspace."""
    raw_prompt: str = Field(min_length=5, description="Initial, potentially vague course description")
    course_title_hint: Optional[str] = Field(default=None, description="Optional suggested course title")
    target_audience: Optional[str] = Field(default=None, description="Optional student cohort description")
    constraints: Optional[dict[str, Any]] = Field(default_factory=dict, description="Optional extra constraints")

    @model_validator(mode="before")
    @classmethod
    def map_prompt_alias(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "prompt" in data and "raw_prompt" not in data:
                data["raw_prompt"] = data["prompt"]
        return data


class ClarificationQuestion(BaseModel):
    """A targeted question generated by the agent to resolve missing course workspace dimensions."""
    question_id: str = Field(description="Unique identifier for the question")
    category: MissingInfoCategory = Field(description="The dimension of missing information")
    question_text: str = Field(description="The clarification question posed to the faculty")
    rationale: str = Field(description="Explanation of why this information is necessary for the plan")
    suggested_options: list[str] = Field(description="Pre-populated suggested choices")
    selected_option: Optional[str] = Field(default=None, description="Faculty's selected option")
    custom_response: Optional[str] = Field(default=None, description="Custom freeform input from faculty")


class ClarificationSubmission(BaseModel):
    """Faculty responses to the agent's clarification questions."""
    request_id: str = Field(description="Trace/Session ID of the initial request")
    original_prompt: str = Field(description="The original faculty request prompt")
    course_code_hint: Optional[str] = Field(default=None, description="Optional course code hint (e.g. 26ECAC401)")
    answers: list[ClarificationQuestion] = Field(min_length=2, description="Completed clarification questions with answers")


ProvenanceType = Literal["COURSE_GROUNDED", "USER_PROVIDED", "UNESTABLISHED"]


class WeeklyMaterial(BaseModel):
    """Notes and learning materials for a specific week or module."""
    week: Optional[int] = Field(default=None, ge=1, description="Week number if scheduled, or None if modular/unscheduled")
    section_label: Optional[str] = Field(default=None, description="Source section identifier e.g. 'Section 1' or 'Section 1.1 & 1.2'")
    title: str = Field(description="Topic/Module title")
    topics: list[str] = Field(min_length=1, description="List of subtopics covered")
    reading_materials: list[str] = Field(description="Required textbook chapters, papers, or articles")
    lecture_notes_summary: str = Field(description="Core conceptual takeaway and notes summary")
    provenance: ProvenanceType = Field(default="COURSE_GROUNDED", description="Source fact vs user provided vs unestablished")
    source_document: Optional[str] = Field(default=None, description="Actual source document backing this material")
    source_section: Optional[str] = Field(default=None, description="Source section heading in course documents")


class AssignmentSpec(BaseModel):
    """Practical assignment, homework, or programming lab specification."""
    assignment_id: str = Field(description="Unique assignment code (e.g. HW1, LAB2, PROJ_FINAL)")
    title: str = Field(description="Assignment title")
    due_week: Optional[int] = Field(default=None, ge=1, description="Week number when the assignment is due (if scheduled)")
    description: str = Field(description="Detailed assignment objective and instructions")
    deliverables: list[str] = Field(min_length=1, description="List of required submission artifacts")
    max_points: int = Field(ge=1, description="Maximum raw points attainable")
    weight_percentage: Optional[float] = Field(default=None, ge=0.0, le=100.0, description="Percentage of total course grade")
    provenance: ProvenanceType = Field(default="USER_PROVIDED", description="Source fact vs user provided vs unestablished")


class GradeBreakdownItem(BaseModel):
    """Assessment component and its grading weight."""
    category: str = Field(description="Category name (e.g. Homework Assignments, Lab Practicals, Midterm Exam, Final Project)")
    weight_percentage: float = Field(ge=0.0, le=100.0, description="Weight percentage in total grade")
    description: str = Field(description="Grading criteria and assessment rules")
    provenance: ProvenanceType = Field(default="USER_PROVIDED", description="Source fact vs user provided vs unestablished")


class CourseWorkspacePlan(BaseModel):
    """Structured course workspace plan strictly centered on Notes/Materials, Assignments, and Grades."""
    plan_id: str = Field(description="Unique identifier for the course workspace plan")
    version: str = Field(default="1.0", description="Semantic version of the plan (e.g. 1.0, 1.1)")
    course_code: str = Field(description="Course identifier code (e.g. 26ECAC401)")
    course_name: str = Field(description="Full course name")
    description: str = Field(description="Overview and pedagogical goals")
    target_audience: str = Field(description="Intended student cohort and level")
    duration_weeks: Optional[int] = Field(default=None, ge=1, le=24, description="Course length in weeks if scheduled, or None if modular/unscheduled")
    organization_type: Literal["WEEKLY_SCHEDULE", "SOURCE_BASED"] = Field(default="SOURCE_BASED", description="Organization format")
    prerequisites: list[str] = Field(default_factory=list, description="Required background knowledge or courses")
    
    # Core Pillars (Grounding vs User-Provided vs Unestablished)
    materials_and_notes: list[WeeklyMaterial] = Field(min_length=1, description="Structured notes & learning materials")
    assignments: list[AssignmentSpec] = Field(default_factory=list, description="Assignments, labs, and deliverables (empty if unestablished)")
    grade_breakdown: list[GradeBreakdownItem] = Field(default_factory=list, description="Weighted grade distribution (empty if unestablished)")
    
    # Provenance tracking
    unestablished_fields: list[str] = Field(default_factory=list, description="Fields that remain unestablished in source material or user input")
    provenance_summary: dict[str, ProvenanceType] = Field(default_factory=dict, description="Summary of provenance for major plan components")

    # Operational metadata
    ta_allocation_hours: Optional[int] = Field(default=None, ge=0, description="Recommended weekly TA staffing hours (None if unestablished)")
    milestones: list[str] = Field(default_factory=list, description="Key course milestones or source sections")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class RevisionRequest(BaseModel):
    """Faculty request to modify or refine an existing course workspace plan."""
    plan_id: str = Field(description="ID of the plan to revise")
    revision_prompt: str = Field(min_length=3, description="Faculty's feedback describing desired changes")
    targeted_sections: Optional[list[str]] = Field(default=None, description="Optional targeted sections to modify")


class StructuredDiffItem(BaseModel):
    """An exact atomic change between two plan versions."""
    section: str = Field(description="Target section (e.g. materials_and_notes, assignments, grade_breakdown, overview)")
    action: Literal["ADDED", "MODIFIED", "REMOVED"] = Field(description="Type of alteration")
    path: str = Field(description="JSON-style property path (e.g. assignments[1].weight_percentage)")
    old_value: Optional[Any] = Field(default=None, description="Previous value before revision")
    new_value: Optional[Any] = Field(default=None, description="New value after revision")
    change_description: str = Field(description="Human-readable explanation of the exact change")


class PlanRevisionResponse(BaseModel):
    """Response payload containing revised plan, version bump, changelog, and exact diffs."""
    previous_version: str = Field(description="Version before revision (e.g. 1.0)")
    current_version: str = Field(description="New version generated (e.g. 1.1)")
    revised_plan: CourseWorkspacePlan = Field(description="The updated course workspace plan")
    changelog_summary: str = Field(description="Synthesized summary of all modifications made")
    structured_diffs: list[StructuredDiffItem] = Field(description="List of exact structured diffs")


class PlanHistoryRecord(BaseModel):
    """Version history tracker maintaining all generated versions of a workspace plan."""
    plan_id: str
    current_version: str
    versions: list[CourseWorkspacePlan]
    revisions: list[PlanRevisionResponse]
