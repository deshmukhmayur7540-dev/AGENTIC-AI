"""Document discovery component for locating and registering Agentic AI course files."""

import hashlib
import logging
import os
import re
from pathlib import Path
from typing import Optional

from app.data.db import get_db_connection
from app.knowledge.models import DiscoveredDocument

from config import settings

DEFAULT_KNOWLEDGE_DIR = Path(settings.knowledge_root) / "agentic_ai"
logger = logging.getLogger(__name__)
SUPPORTED_DOCUMENT_TYPES = {
    "docx", "pptx", "xlsx", "txt", "md", "markdown", "pdf", "csv",
    "png", "jpg", "jpeg", "gif", "webp",
}
SKIP_DIR_NAMES = {
    ".git", ".hg", ".svn", ".venv", "venv", "env", "__pycache__",
    "node_modules", ".pytest_cache", ".mypy_cache", "dist", "build",
}


class DocumentDiscovery:
    """Scans the knowledge directory to discover and validate course documents for Chapters 1-4."""

    def __init__(self, base_dir: Optional[Path | str] = None) -> None:
        self.base_dir = Path(base_dir) if base_dir else DEFAULT_KNOWLEDGE_DIR

    def discover(self) -> list[DiscoveredDocument]:
        """Scan knowledge folder and return sorted list of discovered document records."""
        try:
            course_root = self.base_dir.resolve(strict=True)
        except OSError:
            return []
        if not course_root.is_dir():
            return []

        documents: list[DiscoveredDocument] = []

        for root, dirnames, files in os.walk(course_root, followlinks=False):
            root_path = Path(root)
            dirnames[:] = sorted(
                d for d in dirnames
                if d.lower() not in SKIP_DIR_NAMES and not (root_path / d).is_symlink()
            )
            for fname in sorted(files):
                # Ignore temporary or lock files generated by Office apps (e.g. ~$Doc.docx)
                if fname.startswith("~$") or fname.startswith("."):
                    continue

                fpath = root_path / fname
                suffix = fpath.suffix.lower().lstrip(".")

                if suffix not in SUPPORTED_DOCUMENT_TYPES or fpath.is_symlink():
                    continue

                try:
                    resolved_path = fpath.resolve(strict=True)
                    relative_path = resolved_path.relative_to(course_root).as_posix()
                except (OSError, ValueError):
                    continue

                chapter = self._extract_chapter(Path(relative_path).parent, fname)
                if chapter is None or not 1 <= chapter <= 14:
                    continue

                try:
                    file_bytes = resolved_path.read_bytes()
                    file_hash = hashlib.sha256(file_bytes).hexdigest()
                    file_stat = resolved_path.stat()
                except OSError:
                    continue

                path_hash = hashlib.sha256(relative_path.encode("utf-8")).hexdigest()[:8]
                doc_id = f"doc_ch{chapter}_{suffix}_{path_hash}_{file_hash[:10]}"

                documents.append(
                    DiscoveredDocument(
                        document_id=doc_id,
                        course_code="26ECAC401",
                        course_name="Agentic AI",
                        chapter=chapter,
                        source_filename=fname,
                        source_relative_path=relative_path,
                        source_path=str(resolved_path),
                        document_type=suffix,
                        file_size_bytes=file_stat.st_size,
                        content_hash=file_hash,
                        last_modified=file_stat.st_mtime,
                    )
                )

        # Sort predictably by chapter then source filename
        documents.sort(key=lambda d: (d.chapter or 99, d.source_filename))
        return documents

    @staticmethod
    def discover_course_materials() -> list[DiscoveredDocument]:
        """Discover only live database-backed materials inside the managed storage root."""
        root = Path(settings.course_materials_root).resolve()
        try:
            with get_db_connection() as conn:
                rows = conn.execute(
                    """
                    SELECT m.*, c.name AS category_name
                    FROM course_materials m
                    JOIN material_categories c ON c.category_id = m.category_id
                    WHERE lower(m.extension) IN (
                        'docx', 'pptx', 'xlsx', 'txt', 'md', 'pdf', 'csv',
                        'png', 'jpg', 'jpeg', 'gif', 'webp'
                    )
                    ORDER BY m.uploaded_at, m.material_id
                    """
                ).fetchall()
                folders = {
                    row["folder_id"]: row
                    for row in conn.execute(
                        "SELECT folder_id, parent_folder_id, name, course_id, category_id FROM material_folders"
                    ).fetchall()
                }
        except Exception:
            logger.exception("Could not read database-backed course materials for indexing.")
            raise

        documents: list[DiscoveredDocument] = []
        for row in rows:
            storage_key = row["storage_key"]
            if not re.fullmatch(r"[a-f0-9]{32}\.[a-z0-9]+", storage_key):
                logger.error("Skipping material %s with an invalid storage reference.", row["material_id"])
                continue
            candidate = root / storage_key
            if candidate.is_symlink():
                logger.error("Skipping material %s because its stored path is a symbolic link.", row["material_id"])
                continue
            path = candidate.resolve()
            try:
                path.relative_to(root)
                stat = path.stat()
                if not path.is_file() or stat.st_size != row["size_bytes"]:
                    continue
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
                if digest != row["checksum_sha256"]:
                    logger.error("Skipping material %s because its content hash does not match metadata.", row["material_id"])
                    continue
            except (OSError, ValueError):
                continue

            folder_names: list[str] = []
            folder_id = row["folder_id"]
            folder_chain_valid = True
            while folder_id and folder_id in folders:
                folder = folders[folder_id]
                if folder["course_id"] != row["course_id"] or folder["category_id"] != row["category_id"]:
                    folder_chain_valid = False
                    break
                folder_names.append(folder["name"])
                folder_id = folder["parent_folder_id"]
            if folder_id and folder_id not in folders:
                folder_chain_valid = False
            if not folder_chain_valid:
                logger.error("Skipping material %s because its folder ancestry is inconsistent.", row["material_id"])
                continue
            folder_path = "/".join(reversed(folder_names))
            citation_path = " / ".join(
                item for item in (row["category_name"], folder_path, row["original_filename"]) if item
            )
            documents.append(
                DiscoveredDocument(
                    document_id=f"material-{row['material_id']}-{digest[:12]}",
                    course_code=row["course_id"],
                    course_name=row["course_id"],
                    chapter=row["chapter"],
                    source_filename=row["original_filename"],
                    source_relative_path=citation_path,
                    source_path=str(path),
                    document_type=row["extension"],
                    file_size_bytes=stat.st_size,
                    content_hash=digest,
                    last_modified=stat.st_mtime,
                    category=row["category_name"],
                    lab=row["lab"],
                    folder_path=folder_path,
                    material_id=row["material_id"],
                    title=row["title"],
                    description=row["description"],
                )
            )
        return documents

    @staticmethod
    def _extract_chapter(dir_path: Path, filename: str) -> Optional[int]:
        """Extract the academic chapter number (1-4) from directory name or filename."""
        # 1. Match from directory hierarchy, e.g. knowledge/agentic_ai/chapter_1/
        for part in reversed(dir_path.parts):
            match_dir = re.fullmatch(r"chapter[\s_-]?(\d+)", part, re.IGNORECASE)
            if match_dir:
                return int(match_dir.group(1))

        # 2. Match from filename, e.g. Chapter1_Foundations_of_Agentic_AI.docx
        match_fn = re.search(r"Chapter[\s_-]?(\d+)", filename, re.IGNORECASE)
        if match_fn:
            return int(match_fn.group(1))

        return None
